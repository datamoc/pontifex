import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { compileSources, contentCatalog, extractCatalog, nodesToObjects, validateCatalog } from '@datamoc/mwg/mwl';
import { MATERIAL_ORDER, type VehicleDef } from '../src/data.ts';
import { schemas } from './mwl-schema.ts';
import { parseSpec } from '../src/level.ts';

const sources = readdirSync('content').filter(f => f.endsWith('.mwl')).sort().map(file => ({ file: `content/${file}`, source: readFileSync(`content/${file}`, 'utf8') }));
const game = compileSources(sources, { schemas });
const diagnostics = validateCatalog(game, { rowIdScope: 'file' });
if (diagnostics.length > 0) throw new Error(JSON.stringify(diagnostics, null, 2));
const tables = contentCatalog(game).tables;
function rows(id: string): Record<string, unknown>[] {
  const table = tables.find(t => t.id === id);
  if (!table) throw new Error(`Missing table ${id}`);
  return table.rows.map(row => ({ ...row }));
}
const materialRows = rows('materials');
const vehicleRows = rows('vehicles');
const materialIds = materialRows.map(row => String(row.id));
const vehicleIds = vehicleRows.map(row => String(row.id));
const sprites: VehicleDef['sprite'][] = ['citadine', 'jeep1', 'jeep2', 'train', 'bike', 'bus', 'boat'];
function validateRows(rows: Record<string, unknown>[], expectedIds: readonly string[], positive: string[]): void {
  const ids = rows.map(row => String(row.id));
  if (new Set(ids).size !== ids.length || ids.length !== expectedIds.length || expectedIds.some(id => !ids.includes(id))) {
    throw new Error(`Expected exactly these content ids: ${expectedIds.join(', ')}`);
  }
  for (const row of rows) {
    for (const key of positive) {
      if (typeof row[key] !== 'number' || !Number.isFinite(row[key]) || row[key] <= 0) throw new Error(`${row.id}: ${key} must be positive`);
    }
  }
}
validateRows(materialRows, MATERIAL_ORDER, ['cost', 'maxLen', 'stiffness', 'strength', 'tensionStrength', 'density']);
validateRows(vehicleRows, sprites, ['mass', 'zeroTo100', 'width', 'height']);
for (const row of vehicleRows) {
  if (row.sprite !== row.id) throw new Error(`${row.id}: sprite must match the vehicle id`);
}
// Les niveaux : MWG convertit les nœuds compilés en objets selon le schéma (nombres, booléens, enfants regroupés par tag).
const levelNodes = game.roots.filter((node) => node.tag === 'bridge_level');
const converted = nodesToObjects(levelNodes, schemas);
if (converted.diagnostics.length > 0) throw new Error(JSON.stringify(converted.diagnostics, null, 2));
const ids = new Set<number>();
const levels = converted.value.map((object, index) => {
  const { anchor = [], tower = [], island = [], event = [], view, bridge_solution: solutionObject, ...rest } = object as Record<string, any>;
  const attributes: Record<string, any> = rest;
  const file = levelNodes[index].location?.file;
  const materials = String(attributes.materials).split(',').map((id) => id.trim());
  if (!vehicleIds.includes(attributes.car) || materials.some((id) => !materialIds.includes(id))) throw new Error(`${file}: unknown vehicle or material in ${attributes.name}`);
  if (view && (view.w <= 0 || view.h <= 0)) throw new Error(`${attributes.name}: view dimensions must be positive`);
  const solution = solutionObject ? { nodes: solutionObject.bridge_node ?? [], beams: solutionObject.bridge_beam ?? [] } : undefined;
  const spec: Record<string, any> = { ...attributes, materials, anchors: anchor, towers: tower, islands: island, ...(event.length ? { events: event } : {}), ...(view ? { view } : {}), ...(solution ? { solution } : {}) };
  if (spec.id <= 0) throw new Error(`${attributes.name}: level id must be positive`);
  if (ids.has(spec.id)) throw new Error(`Duplicate level id ${spec.id}`);
  ids.add(spec.id);
  const parsed = parseSpec(spec);
  if ('error' in parsed) throw new Error(`${file}: ${attributes.name}: ${parsed.error}`);
  return spec;
});
const materials = Object.fromEntries(materialRows.map(({ tensionStrength, ...row }) => [String(row.id), {
  ...row, ...(tensionStrength !== row.strength ? { tensionStrength } : {}),
}]));
const vehicles = Object.fromEntries(vehicleRows.map(({ id, ...row }) => [String(id), row]));
const header = '// Generated by npm run content from content/*.mwl. Do not edit.\n';
const output = header + "import type { MaterialDef, MaterialId, VehicleDef } from '../data.ts';\nimport type { LevelSpec } from '../level.ts';\n" +
  `export const MATERIALS: Record<MaterialId, MaterialDef> = ${JSON.stringify(materials, null, 2)};\n` +
  `export const CARS: Record<VehicleDef['sprite'], VehicleDef> = ${JSON.stringify(vehicles, null, 2)};\n` +
  `export const BUILTIN_SPECS: LevelSpec[] = ${JSON.stringify(levels, null, 2)};\n`;
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/content.ts', output);
writeFileSync('content/i18n.fr.json', JSON.stringify(extractCatalog(game, { locale: 'fr' }), null, 2) + '\n');
console.log(`MWL: ${levels.length} levels, ${materialRows.length} materials, ${vehicleRows.length} vehicles validated`);

